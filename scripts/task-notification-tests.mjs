import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const js = ts.transpileModule(fs.readFileSync('app/lib/taskNotifications.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {taskNotices, taskCheckpoint} = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const creator = {user_id:'a', nome:'Ana', setor:'TI'}, assignee = {user_id:'b', nome:'Bruno', setor:'TI'};
const task = {id:'task-1', titulo:'Revisar entrega', setor:'TI', responsavel:'Bruno', atribuido_por:'Ana', chat:[]};
const baseline = taskCheckpoint(task);
const comment = {id:'c1', author:'Bruno', authorId:'b', text:'Etapa pronta'};
const updated = {...task, chat:[comment]};
assert.equal(taskNotices(updated, baseline, creator).length, 1, 'assignee -> creator');
assert.equal(taskNotices(updated, baseline, assignee).length, 0, 'no self notice');
assert.equal(taskNotices({...task,chat:[{...comment, author:'Ana',authorId:'a'}]}, baseline, assignee).length, 1, 'creator -> assignee');
assert.equal(taskNotices({...updated,chat:[{...comment,isAlert:true}]}, baseline, creator)[0].title, 'Atenção no diário da tarefa');
assert.equal(taskNotices({...updated,chat:[{...comment,text:'Editada'}]}, taskCheckpoint(updated), creator).length, 0, 'edit is not a new message');
assert.equal(taskNotices(updated, taskCheckpoint(updated), creator).length, 0, 'replayed event');
assert.equal(taskNotices(updated, baseline, {...creator,nome:'Carla',user_id:'c'}).length, 0, 'unrelated teammate');
assert.equal(taskNotices(updated, baseline, {...creator,setor:'RH'}).length, 0, 'other sector');
assert.equal(taskNotices(task, undefined, assignee).length, 1, 'new assignment');
assert.equal(taskNotices(updated, undefined, creator).length, 0, 'no historical flood');
assert.equal(taskNotices({...task,chat:[comment,{...comment,id:'c2'}]}, baseline, creator).length, 2, 'offline batch');
assert.equal(taskNotices({...task,responsavel:'Ana',atribuido_por:'Ana'}, undefined, creator).length, 0, 'self task');
assert.equal(taskNotices(updated, baseline, creator)[0].link, '/dashboard/tarefas?taskId=task-1&tab=updates');
console.log('PASS: 13 notification routing, replay, privacy and deep-link assertions.');
